#!/bin/sh
# Cross-compile the image, font and video libraries that the "waiting" engines of
# the DOS default build need, for 32-bit MS-DOS with DJGPP, targeting the 486.
#
#   zlib         1.3.1   https://github.com/madler/zlib/releases/download/v1.3.1/zlib-1.3.1.tar.gz
#   libpng       1.6.43  https://download.sourceforge.net/libpng/libpng-1.6.43.tar.xz
#   jpeg (IJG)   9f      https://www.ijg.org/files/jpegsrc.v9f.tar.gz
#   giflib       5.2.2   https://downloads.sourceforge.net/project/giflib/giflib-5.2.2.tar.gz
#   freetype     2.13.2  https://download.savannah.gnu.org/releases/freetype/freetype-2.13.2.tar.xz
#   libmpeg2     0.5.1   https://ftp.osuosl.org/pub/blfs/conglomeration/libmpeg2/libmpeg2-0.5.1.tar.gz
#   libtheora    1.1.1   https://downloads.xiph.org/releases/theora/libtheora-1.1.1.tar.xz  (decoder only)
#
# Same layout as build-libs.sh: sources in $L/src, objects in $L/build, installed in $L/prefix.
#
# zlib and giflib are compiled by hand, the others with their own configure, out of tree. SSE and
# MMX code is off so nothing can trip a 486 (libmpeg2 picks its MMX code at run time).
#
# Usage: build-image-libs.sh [zlib] [png] [jpeg] [gif] [freetype] [mpeg2] [theora]   (default: all)
set -e

# The tool locations (DJGPP_HOME, DJGPP) come from dos-env.sh, the same as for configure-dos.sh
DEPS_DIR=$(cd "$(dirname "$0")" && pwd)
DOS_DIR=$(cd "$DEPS_DIR/.." && pwd)
. "$DOS_DIR/dos-env.sh"
dos_env || exit 1
L=${DEPS_ROOT:-$SRC/build-dos-deps}

HOST=i586-pc-msdosdjgpp
CC=$HOST-gcc
AR=$HOST-ar
RANLIB=$HOST-ranlib
CFLAGS="-O2 -march=i486 -mtune=i486 -fomit-frame-pointer"
P=$L/prefix
JOBS=${JOBS:-8}

mkdir -p "$P/include" "$P/lib"

# Never let a configure script look at the Mac's own libraries
PKG_CONFIG_LIBDIR=$P/lib/pkgconfig
PKG_CONFIG_PATH=
export PKG_CONFIG_LIBDIR PKG_CONFIG_PATH

# compile <srcdir> <builddir> <extra flags> files...
compile() {
  src=$1; bld=$2; flags=$3; shift 3
  mkdir -p "$bld"
  for f in "$@"; do
    o="$bld/$(basename "$f" .c).o"
    $CC $CFLAGS $flags -c "$src/$f" -o "$o"
  done
}

# configured <name> <configure arguments...>: configure, build and install out of tree
configured() {
  name=$1; shift
  B=$L/build/$name
  rm -rf "$B"
  mkdir -p "$B"
  (cd "$B" && \
    CC=$CC AR=$AR RANLIB=$RANLIB CFLAGS="$CFLAGS" CPPFLAGS="-I$P/include" LDFLAGS="-L$P/lib" \
    "$L/src/$name/configure" --host=$HOST --prefix="$P" --disable-shared --enable-static "$@" > configure.log 2>&1)
}

build_zlib() {
  SRC=$L/src/zlib; B=$L/build/zlib
  compile "$SRC" "$B" "-DHAVE_UNISTD_H -DHAVE_STDARG_H -DHAVE_VSNPRINTF -I$SRC" \
    adler32.c crc32.c deflate.c infback.c inffast.c inflate.c inftrees.c trees.c zutil.c \
    compress.c uncompr.c gzclose.c gzlib.c gzread.c gzwrite.c
  rm -f "$B/libz.a"
  $AR rcs "$B/libz.a" "$B"/*.o
  $RANLIB "$B/libz.a"
  cp "$SRC/zlib.h" "$SRC/zconf.h" "$P/include/"
  cp "$B/libz.a" "$P/lib/libz.a"
  echo "zlib: done"
}

build_png() {
  configured libpng --disable-hardware-optimizations
  (cd "$L/build/libpng" && make -j$JOBS libpng16.la > make.log 2>&1 && \
    make install-libLTLIBRARIES install-pkgincludeHEADERS install-nodist_pkgincludeHEADERS install-header-links install-library-links \
      install-pkgconfigDATA install-binSCRIPTS >> make.log 2>&1) || { tail -20 "$L/build/libpng/make.log"; return 1; }
  echo "libpng: done"
}

build_jpeg() {
  configured jpeg
  (cd "$L/build/jpeg" && make -j$JOBS libjpeg.la > make.log 2>&1 && \
    make install-libLTLIBRARIES install-includeHEADERS >> make.log 2>&1) || { tail -20 "$L/build/jpeg/make.log"; return 1; }
  # jconfig.h is generated by configure and is not installed by the makefile
  cp "$L/build/jpeg/jconfig.h" "$P/include/jconfig.h"
  echo "jpeg: done"
}

build_gif() {
  SRC=$L/src/giflib; B=$L/build/giflib
  compile "$SRC" "$B" "-std=gnu99 -I$SRC" \
    dgif_lib.c egif_lib.c gifalloc.c gif_err.c gif_font.c gif_hash.c openbsd-reallocarray.c
  rm -f "$B/libgif.a"
  $AR rcs "$B/libgif.a" "$B"/*.o
  $RANLIB "$B/libgif.a"
  cp "$SRC/gif_lib.h" "$P/include/"
  cp "$B/libgif.a" "$P/lib/libgif.a"
  echo "giflib: done"
}

build_freetype() {
  # freetype builds a small helper program that has to run on this Mac
  CC_BUILD=cc
  export CC_BUILD
  # --enable-freetype-config: ScummVM's configure looks for that script (newer
  # FreeType no longer installs it by default)
  configured freetype --enable-freetype-config --without-zlib --without-bzip2 --without-png --without-harfbuzz --without-brotli
  (cd "$L/build/freetype" && make -j$JOBS > make.log 2>&1 && make install >> make.log 2>&1) \
    || { tail -20 "$L/build/freetype/make.log"; return 1; }

  # The freetype-config that FreeType installs asks the host's pkg-config for its
  # answers, which finds the Mac's FreeType. Replace it with one that only knows
  # this prefix.
  printf '%s\n' \
    '#!/bin/sh' \
    '# freetype-config for the DJGPP build of FreeType 2.13.2 in this prefix' \
    "prefix=$P" \
    'for arg in "$@"; do' \
    '  case "$arg" in' \
    '    --prefix=*) prefix=${arg#--prefix=} ;;' \
    '  esac' \
    'done' \
    'for arg in "$@"; do' \
    '  case "$arg" in' \
    '    --prefix|--exec-prefix) echo "$prefix" ;;' \
    '    --version) echo 24.2.18 ;;' \
    '    --ftversion) echo 2.13.2 ;;' \
    '    --cflags) echo "-I$prefix/include/freetype2" ;;' \
    '    --libs) echo "-L$prefix/lib -lfreetype" ;;' \
    '  esac' \
    'done' > "$P/bin/freetype-config"
  chmod +x "$P/bin/freetype-config"
  echo "freetype: done"
}

build_mpeg2() {
  # Only the decoder: the colour conversion helper (libmpeg2convert) wants
  # 32-byte alignment, which DJGPP's file format cannot give, and ScummVM does
  # its own conversion
  configured libmpeg2 --disable-sdl
  (cd "$L/build/libmpeg2" && make -j$JOBS -C include > make.log 2>&1 && make -j$JOBS -C libmpeg2 libmpeg2.la >> make.log 2>&1 && \
    make -C include install >> make.log 2>&1 && make -C libmpeg2 install-libLTLIBRARIES >> make.log 2>&1) \
    || { tail -20 "$L/build/libmpeg2/make.log"; return 1; }
  echo "libmpeg2: done"
}

build_theora() {
  configured libtheora --disable-encode --disable-examples --disable-doc --disable-spec \
    --disable-oggtest --disable-vorbistest --disable-asm --with-ogg="$P"
  (cd "$L/build/libtheora" && make -j$JOBS -C lib > make.log 2>&1 && make -C lib install >> make.log 2>&1 && \
    make -C include install >> make.log 2>&1) \
    || { tail -20 "$L/build/libtheora/make.log"; return 1; }
  echo "libtheora: done"
}

if [ $# -eq 0 ]; then
  set -- zlib png jpeg gif freetype mpeg2 theora
fi
for what in "$@"; do
  "build_$what"
done
