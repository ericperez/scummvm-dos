import struct
import subprocess
import sys

# Make an 8x8 test picture (left half red, right half blue) and have macOS convert it to
# PNG, JPEG and GIF, then write all three as C arrays for the DOS library test.
out = sys.argv[1]
w = h = 8
row = b"".join((b"\x00\x00\xff" if x < 4 else b"\xff\x00\x00") for x in range(w))  # BGR
pix = row * h
bmp = b"BM" + struct.pack("<IHHI", 54 + len(pix), 0, 0, 54)
bmp += struct.pack("<IiiHHIIiiII", 40, w, h, 1, 24, 0, len(pix), 2835, 2835, 0, 0) + pix
open(out + "/t.bmp", "wb").write(bmp)
for fmt, ext in (("png", "png"), ("jpeg", "jpg"), ("gif", "gif")):
    subprocess.check_call(["sips", "-s", "format", fmt, out + "/t.bmp", "--out", out + "/t." + ext],
                          stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

lines = ["/** generated by mkimgs.py: an 8x8 picture, left half red, right half blue */"]
for ext in ("png", "jpg", "gif"):
    data = open(out + "/t." + ext, "rb").read()
    lines.append("static const unsigned char test_%s[] = {" % ext)
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("static const unsigned test_%s_len = %d;" % (ext, len(data)))
open(out + "/libtest-data.h", "w").write("\n".join(lines) + "\n")
print("png/jpg/gif sizes:", [len(open(out + "/t." + e, "rb").read()) for e in ("png", "jpg", "gif")])
