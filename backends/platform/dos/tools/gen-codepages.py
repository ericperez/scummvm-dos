#!/usr/bin/env python3
"""Generate dos-codepages.h: the upper half (0x80..0xFF) of the DOS code pages as Unicode.

The tables come from Python's own codecs (cp437, cp850, ...), not from memory, so they
are as right as Python's. Run from anywhere:

    python3 backends/platform/dos/tools/gen-codepages.py > backends/platform/dos/dos-codepages.h
"""
